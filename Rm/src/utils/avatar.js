// ตัดคำนำหน้าไทย/คำนำหน้าตำแหน่งออกก่อน เอาตัวอักษรแรกของ "ชื่อจริง" มาทำวงกลม
// ไม่งั้นทุกคนจะได้ตัว "น"/"ค" ซ้ำกันหมดเพราะคำนำหน้าไทยส่วนใหญ่ขึ้นต้นด้วยคำเดียวกัน (เช่น "คุณครูสุพรรณี" ต้องได้ตัว "ส" ไม่ใช่ "ค")
export const initialOf = (fullname = "") => {
  const stripped = (fullname || "").replace(/^(นางสาว|เด็กหญิง|เด็กชาย|คุณครู|นาย|นาง|ครู|คุณ)\s*/u, "");
  return (stripped || fullname || "?").trim().charAt(0) || "?";
};
